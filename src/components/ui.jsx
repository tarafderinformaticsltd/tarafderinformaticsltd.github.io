export function Icon({ name, size }) {
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      <path d={PATHS[name]} />
    </svg>
  );
}

/** Renders [{t, grad}] heading parts, using the brand gradient for grad parts. */
export function Heading({ parts }) {
  return parts.map((p, i) =>
    p.grad ? (
      <span key={i} className="grad-text">{p.t}</span>
    ) : (
      <span key={i}>{p.t}</span>
    )
  );
}

export function Reveal({ as: Tag = "div", delay = 0, className = "", children, ...rest }) {
  const ref = useRef(null);
  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const io = new IntersectionObserver(
      ([e]) => {
        if (e.isIntersecting) {
          el.classList.add("in");
          io.disconnect();
        }
      },
      { threshold: 0.12 }
    );
    io.observe(el);
    return () => io.disconnect();
  }, []);
  const d = delay ? ` d${delay}` : "";
  return (
    <Tag ref={ref} className={`reveal${d} ${className}`.trim()} {...rest}>
      {children}
    </Tag>
  );
}

export function Button({ href, variant = "brand", size, arrow, className = "", children, ...rest }) {
  const cls = ["btn", `btn-${variant}`, size === "sm" ? "btn-sm" : "", className].filter(Boolean).join(" ");
  return (
    <a href={href} className={cls} {...rest}>
      {children}
      {arrow && <Icon name="arrowRight" />}
    </a>
  );
}

export function SecHead({ eyebrow, heading, text }) {
  return (
    <Reveal className="sec-head">
      <span className="eyebrow">{eyebrow}</span>
      <h2><Heading parts={heading} /></h2>
      <p>{text}</p>
    </Reveal>
  );
}

